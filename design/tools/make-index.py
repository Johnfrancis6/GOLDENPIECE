#!/usr/bin/env python3
"""Writes design/INDEX.md: every design file with its headings and line numbers, so a session reads
only the section it needs (sed -n 'START,ENDp' file) instead of whole files (HANDOFF alone is 33 KB).
Usage: python3 design/tools/make-index.py"""
import pathlib, re
D = pathlib.Path(__file__).resolve().parent.parent
R = D.parent
files = sorted(p for p in D.rglob('*.md') if 'previews' not in p.parts and p.name != 'INDEX.md')
files += [R / 'docs' / n for n in ('BRIEF_03_DESIGN.md', 'CHALLENGES.md') if (R / 'docs' / n).exists()]
out = ['# Design index (generated by tools/make-index.py — do not edit)', '',
       'Read a section with `sed -n "A,Bp" <file>` (A = heading line, B = next heading line - 1).', '']
for f in files:
    lines = f.read_text().split('\n')
    kb = round(len(f.read_bytes()) / 1024)
    heads = [(i + 1, l) for i, l in enumerate(lines) if re.match(r'#{1,2} ', l)]
    out.append(f'## {f.relative_to(R)} ({kb} KB, {len(lines)} lines)')
    out += [f'- {n}: {h.strip()}' for n, h in heads[:40]]
    out.append('')
(D / 'INDEX.md').write_text('\n'.join(out))
print(f'INDEX.md: {len(files)} files')
