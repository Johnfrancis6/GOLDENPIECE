export const STRINGS = { fr, en } as const;
export type StringKey = Key;

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Server error message keys (API.md §1) → text. */
export function errorText(lang: Lang, messageKey: string | undefined): string {
  const d = (lang === 'en' ? sharedEn : sharedFr).error as Record<string, string>;
  return (messageKey && d[messageKey]) || d.generic;
}

export const LangContext = createContext<Lang>('fr');
export function useT() {
  const lang = useContext(LangContext);
  return Object.assign((key: StringKey, params?: Record<string, string | number>) => translate(lang, key, params), { lang });
}
