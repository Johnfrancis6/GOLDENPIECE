#!/usr/bin/env python3
"""IBAN fixtures (UEMOA 28 / CEMAC 27 / FR 27) shared by Python and pgTAP.
  python3 shared/fixtures/gen_iban.py   → shared/fixtures/iban.json + supabase/tests/iban_fixtures.test.sql
"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "batch"))
from goldenpiece.generator import iban as ib  # noqa: E402

rng = random.Random("gp-iban-2026")
cases = []
for country, bank in [("SN", "SN901"), ("SN", "SN902"), ("CI", "CI901"), ("ML", "ML901"), ("SN", "SN900"),
                      ("CM", "10901"), ("GA", "40901"), ("CM", "10900"), ("FR", "99901"), ("FR", "99900")]:
    for _ in range(3):
        branch = f"{rng.randint(0, 99999):05d}"
        acc = "".join(str(rng.randint(0, 9)) for _ in range(ib.account_length(country)))
        cases.append({"country": country, "bank": bank, "branch": branch, "account": acc,
                      "iban": ib.iban(country, bank, branch, acc)})
(ROOT / "shared/fixtures/iban.json").write_text(json.dumps(cases, indent=1) + "\n")
lines = ["-- GENERATED by shared/fixtures/gen_iban.py — do not edit.", "begin;",
         "create extension if not exists pgtap with schema extensions;", "set search_path = extensions, public;",
         f"select plan({len(cases)});"]
for c in cases:
    lines.append(f"select is(sim.iban('{c['country']}', '{c['bank']}', '{c['branch']}', '{c['account']}'), "
                 f"'{c['iban']}', 'iban {c['country']} {c['bank']}');")
lines += ["select * from finish();", "rollback;"]
(ROOT / "supabase/tests/iban_fixtures.test.sql").write_text("\n".join(lines) + "\n")
